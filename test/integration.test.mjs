import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const exec=promisify(execFile);
const base=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const runtime=process.env.AUDITOR_BUILD==='1'?'dist':'src';
const runtimeDir=process.env.AUDITOR_RUNTIME_DIR || path.join(base,runtime);
test('real stdio MCP handshake, all tools, CLI parity, and scope enforcement',async t=>{
  const temp=process.platform==='darwin'?await fs.realpath(os.tmpdir()):os.tmpdir();
  const root=await fs.mkdtemp(path.join(temp,'auditor-mcp-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  await fs.mkdir(path.join(root,'outputs'));
  await fs.writeFile(path.join(root,'outputs','sample.txt'),'hello');
  const client=new Client({name:'integration-test',version:'1.0.0'});
  await client.connect(new StdioClientTransport({command:process.execPath,args:[path.join(runtimeDir,'server.mjs'),root],stderr:'pipe'}));
  t.after(()=>client.close());
  assert.equal((await client.listTools()).tools.length,3);
  const result=await client.callTool({name:'scan_storage',arguments:{roots:[root]}});
  const mcp=JSON.parse(result.content[0].text);
  const cli=JSON.parse((await exec(process.execPath,[path.join(runtimeDir,'cli.mjs'),'scan_storage','--root',root])).stdout);
  assert.deepEqual(mcp.totals,cli.totals); assert.equal(mcp.totals.bytes,5);
  const description=await client.callTool({name:'describe_folder',arguments:{path:path.join(root,'outputs')}});
  assert.equal(JSON.parse(description.content[0].text).category,'generated outputs');
  const denied=await client.callTool({name:'describe_folder',arguments:{path:path.dirname(root)}});
  assert.equal(denied.isError,true);
  const attempted=await client.callTool({name:'scan_storage',arguments:{roots:[path.dirname(root)]}});
  assert.equal(JSON.parse(attempted.content[0].text).totals.bytes,0);
  assert.equal((await client.callTool({name:'scan_storage',arguments:{allowedRoots:[path.dirname(root)]}})).isError,true);
  assert.ok((await client.callTool({name:'discover_agents',arguments:{}})).content.length);
});
